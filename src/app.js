(function () {
  const type = document.getElementById('type');
  const seats = document.getElementById('seats');
  const student = document.getElementById('student');
  const total = document.getElementById('total');
  const error = document.getElementById('error');

  function update() {
    try {
      const amount = Pricing.calculateTotal(type.value, parseInt(seats.value, 10), student.checked);
      total.textContent = 'PKR ' + amount.toLocaleString();
      error.textContent = '';
    } catch (e) {
      total.textContent = '-';
      error.textContent = e.message;
    }
  }

  [type, seats, student].forEach((el) => el.addEventListener('input', update));
  update();

  // build-info.json is generated by the CI pipeline at build time
  fetch('build-info.json', { cache: 'no-store' })
    .then((r) => r.json())
    .then((b) => {
      document.getElementById('build').textContent =
        'Version ' + b.version + ' | commit ' + b.commit.slice(0, 7) + ' | built ' + b.builtAt;
    })
    .catch(() => {
      document.getElementById('build').textContent = 'Version: local dev';
    });
})();
